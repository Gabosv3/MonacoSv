insert into role_permissions (role_id, permission)
select r.id, p.name
from roles r, permissions p
where r.name in ('super-admin', 'admin') and p.module in ('Clientes', 'Cotizaciones')
on conflict do nothing;

insert into role_permissions (role_id, permission)
select r.id, p
from roles r, unnest(array['customers.view', 'customers.create', 'customers.edit', 'quotes.view', 'quotes.create', 'quotes.edit']) as p
where r.name = 'vendedor'
on conflict do nothing;

