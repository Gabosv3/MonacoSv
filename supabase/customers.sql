-- ------------------------------------------------------------
-- Clientes
-- ------------------------------------------------------------

create table if not exists customers (
  id uuid primary key default gen_random_uuid(),
  name text not null default '',
  phone text not null default '',
  -- el teléfono solo con dígitos: así "7000-1111" y "70001111" son la misma persona
  phone_key text generated always as (regexp_replace(phone, '\D', '', 'g')) stored,
  email text not null default '',
  department text not null default '',
  municipality text not null default '',
  address text not null default '',
  notes text not null default '',
  source text not null default 'admin' check (source in ('tienda', 'admin', 'whatsapp')),
  created_at timestamptz not null default now()
);

create unique index if not exists customers_phone_key_idx on customers (phone_key) where phone_key <> '';

alter table sales add column if not exists customer_id uuid references customers(id) on delete set null;
create index if not exists sales_customer_idx on sales (customer_id);

-- ------------------------------------------------------------
-- Cotizaciones
-- ------------------------------------------------------------

create table if not exists quotes (
  id uuid primary key default gen_random_uuid(),
  quote_number bigint generated by default as identity (start with 101),
  customer_id uuid not null references customers(id) on delete cascade,
  status text not null default 'abierta' check (status in ('abierta', 'enviada', 'ganada', 'perdida')),
  source text not null default 'admin' check (source in ('tienda', 'admin')),
  notes text not null default '',
  valid_until date,
  total numeric(12, 2) not null default 0,
  converted_sale_id uuid references sales(id) on delete set null,
  created_at timestamptz not null default now()
);
create unique index if not exists quotes_number_idx on quotes (quote_number);
create index if not exists quotes_customer_idx on quotes (customer_id);

create table if not exists quote_items (
  id uuid primary key default gen_random_uuid(),
  quote_id uuid not null references quotes(id) on delete cascade,
  product_id uuid references products(id) on delete set null,
  product_name text not null default '',
  quantity integer not null check (quantity > 0),
  unit_price numeric(12, 2) not null default 0,
  subtotal numeric(12, 2) generated always as (quantity * unit_price) stored
);
create index if not exists quote_items_quote_idx on quote_items (quote_id);

-- ------------------------------------------------------------
-- Cada pedido registra o actualiza a su cliente
-- ------------------------------------------------------------

create or replace function link_sale_customer()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  k text;
  cid uuid;
begin
  if new.customer_id is not null then
    return new;
  end if;

  k := regexp_replace(coalesce(new.customer_phone, ''), '\D', '', 'g');
  if k = '' and coalesce(new.customer_name, '') = '' then
    return new; -- pedido anónimo: no hay a quién registrar
  end if;

  if k <> '' then
    select id into cid from customers where phone_key = k;
  end if;

  if cid is null then
    insert into customers (name, phone, department, municipality, address, source)
    values (
      coalesce(new.customer_name, ''), coalesce(new.customer_phone, ''),
      coalesce(new.department, ''), coalesce(new.municipality, ''), coalesce(new.address, ''),
      case when new.source = 'tienda' then 'tienda' else 'admin' end
    )
    on conflict (phone_key) where phone_key <> '' do nothing
    returning id into cid;
    if cid is null and k <> '' then
      select id into cid from customers where phone_key = k;
    end if;
  else
    -- completa datos que le faltaban al cliente, sin pisar los que ya tiene
    update customers set
      name = case when name = '' then coalesce(new.customer_name, '') else name end,
      department = case when department = '' then coalesce(new.department, '') else department end,
      municipality = case when municipality = '' then coalesce(new.municipality, '') else municipality end,
      address = case when address = '' then coalesce(new.address, '') else address end
    where id = cid;
  end if;

  new.customer_id := cid;
  return new;
end;
$$;

-- Se llama "zz_" para correr después de sanitize_public_sale_trg
drop trigger if exists zz_link_sale_customer on sales;
create trigger zz_link_sale_customer
  before insert on sales
  for each row execute function link_sale_customer();

-- Un pedido anónimo (de la tienda) no puede elegir a qué cliente pertenece
create or replace function sanitize_public_sale()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if auth.uid() is null then
    new.status := 'pendiente';
    new.source := 'tienda';
    new.courier_id := null;
    new.invoiced := false;
    new.invoiced_at := null;
    new.customer_id := null;
  end if;
  return new;
end;
$$;

-- ------------------------------------------------------------
-- Cotizar desde la tienda (sin cuenta): crea el cliente y la cotización
-- ------------------------------------------------------------

create or replace function request_quote(
  p_name text,
  p_phone text,
  p_notes text,
  p_items jsonb,
  p_department text default '',
  p_municipality text default ''
)
returns bigint
language plpgsql security definer set search_path = public
as $$
declare
  k text := regexp_replace(coalesce(p_phone, ''), '\D', '', 'g');
  cid uuid;
  qid uuid;
  qnum bigint;
  item jsonb;
  prod products;
  qty integer;
  price numeric;
  v_total numeric := 0;
begin
  if coalesce(trim(p_name), '') = '' and k = '' then
    raise exception 'Escribe tu nombre o tu teléfono para registrar la cotización.';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 30 then
    raise exception 'La cotización necesita entre 1 y 30 productos.';
  end if;

  if k <> '' then
    select id into cid from customers where phone_key = k;
  end if;
  if cid is null then
    insert into customers (name, phone, department, municipality, source)
    values (left(coalesce(p_name, ''), 120), left(coalesce(p_phone, ''), 40), left(coalesce(p_department, ''), 60), left(coalesce(p_municipality, ''), 80), 'tienda')
    on conflict (phone_key) where phone_key <> '' do nothing
    returning id into cid;
    if cid is null then
      select id into cid from customers where phone_key = k;
    end if;
  end if;

  insert into quotes (customer_id, source, notes)
  values (cid, 'tienda', left(coalesce(p_notes, ''), 500))
  returning id, quote_number into qid, qnum;

  for item in select * from jsonb_array_elements(p_items) loop
    qty := greatest(1, least(999, coalesce((item->>'quantity')::integer, 1)));
    prod := null;
    begin
      select * into prod from products where id = (item->>'product_id')::uuid;
    exception when others then
      prod := null;
    end;
    -- el precio sale de la base de datos siempre que el producto exista
    price := coalesce(
      case when prod.id is not null then
        case when prod.sale_price is not null and prod.sale_price < prod.price then prod.sale_price else prod.price end
      end,
      least(10000, greatest(0, coalesce((item->>'unit_price')::numeric, 0)))
    );
    insert into quote_items (quote_id, product_id, product_name, quantity, unit_price)
    values (qid, prod.id, left(coalesce(prod.name || case when prod.volume <> '' then ' (' || prod.volume || ')' else '' end, item->>'product_name', ''), 160), qty, price);
    v_total := v_total + qty * price;
  end loop;

  update quotes set total = v_total where id = qid;
  return qnum;
end;
$$;

grant execute on function request_quote(text, text, text, jsonb, text, text) to anon, authenticated;

-- ------------------------------------------------------------
-- Datos que ya existen: clientes desde los pedidos anteriores
-- ------------------------------------------------------------

insert into customers (name, phone, department, municipality, address, source, created_at)
select distinct on (s.k)
  s.customer_name, s.customer_phone,
  coalesce(s.department, ''), coalesce(s.municipality, ''), coalesce(s.address, ''),
  case when s.source = 'tienda' then 'tienda' else 'admin' end,
  s.created_at
from (select *, regexp_replace(coalesce(customer_phone, ''), '\D', '', 'g') as k from sales) s
where s.k <> ''
order by s.k, s.created_at asc
on conflict do nothing;

update sales s
set customer_id = c.id
from customers c
where s.customer_id is null
  and c.phone_key <> ''
  and c.phone_key = regexp_replace(coalesce(s.customer_phone, ''), '\D', '', 'g');

